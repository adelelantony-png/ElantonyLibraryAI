    def create_p(align=WD_ALIGN_PARAGRAPH.RIGHT, space_before=2, space_after=2, line_spacing=1.15):
        p = doc.add_paragraph()
        p.paragraph_format.bidi = True
        p.alignment = align
        p.paragraph_format.space_before = Pt(space_before)
        p.paragraph_format.space_after = Pt(space_after)
        p.paragraph_format.line_spacing = line_spacing
        return p

    def add_ar_run(p, text, size_pt=11, bold=False, color=None):
        r = p.add_run(text)
        r.font.name = FONT_NAME
        r.font.size = Pt(size_pt)
        r.bold = bold
        if color:
            r.font.color.rgb = color
            
        rPr = r._r.get_or_add_rPr()
        
        # Ensure single clean rFonts element with ascii, hAnsi, and cs all set to Arial
        existing_fonts = rPr.findall(qn('w:rFonts'))
        for ef in existing_fonts:
            rPr.remove(ef)
        rFonts = parse_xml(f'<w:rFonts {nsdecls("w")} w:ascii="{FONT_NAME}" w:hAnsi="{FONT_NAME}" w:cs="{FONT_NAME}"/>')
        rPr.append(rFonts)
        
        # Add RTL marker so Word knows this is right-to-left Arabic text
        if rPr.find(qn('w:rtl')) is None:
            rPr.append(parse_xml(f'<w:rtl {nsdecls("w")} w:val="1"/>'))
            
        # Add Complex Script bold if bold is true
        if bold:
            if rPr.find(qn('w:bCs')) is None:
                rPr.append(parse_xml(f'<w:bCs {nsdecls("w")} w:val="1"/>'))
                
        # Set Arabic language tag
        if rPr.find(qn('w:lang')) is None:
            rPr.append(parse_xml(f'<w:lang {nsdecls("w")} w:bidi="ar-EG"/>'))
            
        return r

