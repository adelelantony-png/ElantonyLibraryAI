def get_all_categories():
    """Returns unique categories."""
    cats = []
    for item in APOLOGETICS_TOPICS:
        if item["category"] not in cats:
            cats.append(item["category"])
    return cats

def get_questions_by_category(category):
    """Returns list of question titles for a given category."""
    return [item for item in APOLOGETICS_TOPICS if item["category"] == category]

def find_topic_by_question(question_text):
    """Finds matching apologetics topic entry."""
    for item in APOLOGETICS_TOPICS:
        if item["question"] == question_text:
            return item
    return None
